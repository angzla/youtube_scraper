import os
import re
import time
from datetime import datetime, timezone
import yt_dlp
import random
import json, glob, tempfile, csv 

# Replace this with your target YouTube playlist URL
PLAYLIST_URL = "https://www.youtube.com/playlist?list=PLdknZ-MFYTTo"

# Replace with what browser you are using! May have more errors with chrome (need to give permission), default is safari
COOKIE_OPTS = {
    # read cookies straight from your browser (log into YouTube there first, then close browser)
    'cookiesfrombrowser': ('safari',),   # or 'firefox', 'edge', 'brave', 'safari'
    # 'cookiesfrombrowser': ('chrome',),
}

CSV_PATH = "transcripts.csv"
CSV_COLUMNS = [
    "Video Title", "Date Posted", "Location",
    "Creator Name", "View Count", "Hashtags", "Subscriber Count",
    "Transcript Type", "Video URL", "Transcript", "Date of Extraction",
]

def filename_component(value):
    """Make a short, filesystem-safe, hyphen-separated filename component."""
    value = re.sub(r'[^\w-]+', '-', str(value), flags=re.UNICODE)
    return value.encode('utf-8')[:90].decode('utf-8', errors='ignore').strip('-') or 'Unknown'

def format_count(value):
    return f"{value:,}" if isinstance(value, (int, float)) else 'Not available'

def format_upload_date(value):
    try:
        return datetime.strptime(value, '%Y%m%d').date().isoformat()
    except (TypeError, ValueError):
        return 'Not available'

def build_metadata(metadata, is_generated, video_id, extracted_at):
    hashtags = list(dict.fromkeys(re.findall(
        r'(?<!\w)#[\w]+',
        f"{metadata.get('title') or ''}\n{metadata.get('description') or ''}",
        flags=re.UNICODE
    )))
    return {
        "Video Title": metadata.get('title') or 'Not available',
        "Date Posted": format_upload_date(metadata.get('upload_date')),
        "Date of Extraction": f"{extracted_at.isoformat(timespec='seconds')} (UTC)",
        "Location": metadata.get('location') or 'Not available',
        "Creator Name": metadata.get('channel') or metadata.get('uploader') or 'Not available',
        "View Count": format_count(metadata.get('view_count')),
        "Hashtags": ' '.join(hashtags) or 'Not available',
        "Subscriber Count": format_count(metadata.get('channel_follower_count')),
        "Transcript Type": 'Autogenerated' if is_generated else 'Manually written',
        "Video URL": f"https://www.youtube.com/watch?v={video_id}",
    }

def get_playlist_video_ids(playlist_url):
    """Extracts all video IDs from a YouTube playlist URL"""
    print("Extracting video IDs from the playlist... Please wait.")
    
    # only fetch metadata, not download actual video files
    ydl_opts = {
        'extract_flat': 'in_playlist', 
        'quiet': True,
        'skip_download': True,
        **COOKIE_OPTS,
    }
    
    video_ids = []
    with yt_dlp.YoutubeDL(ydl_opts) as ydl:
        try:
            playlist_dict = ydl.extract_info(playlist_url, download=False)
            if 'entries' in playlist_dict:
                for entry in playlist_dict['entries']:
                    if entry and 'id' in entry:
                        video_ids.append(entry['id'])
        except Exception as e:
            print(f"Error fetching playlist details: {e}")
            
    return video_ids

def get_transcript_via_ytdlp(video_id):
    """Return (text, is_generated) using yt-dlp's subtitle download."""
    with tempfile.TemporaryDirectory() as tmp:
        opts = {
            'quiet': True,
            'no_warnings': True,
            'skip_download': True,
            'ignore_no_formats_error': True,
            'writesubtitles': True,
            'writeautomaticsub': True,
            'subtitleslangs': ['en.*', 'en'],
            'subtitlesformat': 'json3',
            'outtmpl': os.path.join(tmp, '%(id)s.%(ext)s'),
            **COOKIE_OPTS,
        }
        with yt_dlp.YoutubeDL(opts) as ydl:
            info = ydl.extract_info(
                f"https://www.youtube.com/watch?v={video_id}", download=True
            ) or {}

        files = glob.glob(os.path.join(tmp, f"{video_id}*.json3"))
        if not files:
            raise RuntimeError("No English captions found")

        with open(files[0], encoding='utf-8') as f:
            data = json.load(f)
        text = " ".join(
            seg.get('utf8', '')
            for ev in data.get('events', [])
            for seg in ev.get('segs', []) or []
        )
        text = re.sub(r'\s+', ' ', text).strip()

        # Manual subs exist in info['subtitles']; otherwise they were automatic
        manual = any(k.startswith('en') for k in (info.get('subtitles') or {}))
        return text, (not manual), info

def load_saved_urls(csv_path=CSV_PATH):
    """URLs already in the CSV, so re-runs don't add duplicate rows."""
    if not os.path.exists(csv_path):
        return set()
    with open(csv_path, encoding="utf-8-sig", newline="") as f:
        return {row.get("Video URL") for row in csv.DictReader(f)}

def append_csv_row(fields, transcript, csv_path=CSV_PATH):
    new_file = not os.path.exists(csv_path) or os.path.getsize(csv_path) == 0
    with open(csv_path, "a", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS, quoting=csv.QUOTE_ALL)
        if new_file:
            writer.writeheader()
        writer.writerow({**fields, "Transcript": transcript})

def download_transcripts_from_playlist(playlist_url, output_folder="transcripts"):
    # 1. Create a folder to store the transcripts if it doesn't exist
    if not os.path.exists(output_folder):
        os.makedirs(output_folder)
        
    # 2. Extract the video IDs
    video_ids = get_playlist_video_ids(playlist_url)
    total_videos = len(video_ids)
    print(f"Found {total_videos} videos in the playlist.\n")

    # 3. Check saved urls 
    saved_urls = load_saved_urls()
    
    # 4. Loop through each ID and fetch the transcript
    for index, video_id in enumerate(video_ids, 1):
        print(f"[{index}/{total_videos}] Processing Video ID: {video_id}...")
        
        try:
            full_text, is_generated, metadata = get_transcript_via_ytdlp(video_id)
            extracted_at = datetime.now(timezone.utc)
            fields = build_metadata(metadata, is_generated, video_id, extracted_at)
            
            # Save metadata above the transcript, using channel/title/upload date.
            channel = filename_component(metadata.get('channel') or metadata.get('uploader') or 'Unknown-Channel')
            title = filename_component(metadata.get('title') or video_id)
            upload_date = format_upload_date(metadata.get('upload_date'))
            date_component = upload_date if upload_date != 'Not available' else 'Unknown-Date'
            filename = f"{channel}_{title}_{date_component}.txt"
            file_path = os.path.join(output_folder, filename)
            # Avoid overwriting distinct videos with the same filename.
            if os.path.exists(file_path):
                print(f"  -> Text file already exists, skipping: {file_path}")   
            else: 
                header = '\n'.join(f"{label}: {value}" for label, value in fields.items())
                with open(file_path, "w", encoding="utf-8") as f:
                    f.write(f"{header}\n\nTranscript:\n\n{full_text}")
                
                print(f"  -> Saved successfully: {file_path}")
                        # CSV row: one per video, skipped if already recorded.
            
            if fields["Video URL"] in saved_urls:
                print("  -> Already in CSV, skipping row")
            else:
                append_csv_row(fields, full_text)
                saved_urls.add(fields["Video URL"])
                print(f"  -> Added to {CSV_PATH}")
            
        except Exception as e:
            print(f"  -> Skipping video {video_id}. Error: {e}")
            
        # Sleep random 4-8 seconds to avoid being blocked by YouTube
        time.sleep(random.uniform(4, 8))

if __name__ == "__main__":
    download_transcripts_from_playlist(PLAYLIST_URL)
